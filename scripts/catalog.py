"""Regenerate the read-only catalog and verified rig inventory (stdlib only)."""
import json, struct, re
from pathlib import Path
from collections import Counter

def inspect_fbx(p):
    b=p.read_bytes(); wide=int.from_bytes(b[23:27],'little')>=7500; fmt='<QQQ' if wide else '<III'; head=struct.calcsize(fmt); records=[]
    def node(i):
        end,n,size=struct.unpack_from(fmt,b,i); i+=head
        if end==0:return 0
        ln=b[i]; tag=b[i+1:i+1+ln].decode(); i+=ln+1; child=i+size
        if tag in ('Model','AnimationStack','C'):
            args=[]
            for _ in range(n):
                typ=chr(b[i]);i+=1
                if typ=='S':
                    ln=int.from_bytes(b[i:i+4],'little'); i+=4;args.append(b[i:i+ln].split(b'\0')[0].decode(errors='replace'));i+=ln
                elif typ=='I':args.append(struct.unpack_from('<i',b,i)[0]);i+=4
                elif typ=='L':args.append(struct.unpack_from('<q',b,i)[0]);i+=8
                else:break
            records.append((tag,args))
        while child+head<end:
            child=node(child)
            if not child:break
        return end
    pos=27
    while pos:pos=node(pos)
    bones={a[0]:a[1] for t,a in records if t=='Model' and len(a)==3 and a[2] in ('LimbNode','Root')};parents={a[1]:a[2] for t,a in records if t=='C' and len(a)>=3 and a[0]=='OO' and a[2] in bones}
    return {'bones':{v:bones.get(parents.get(k)) for k,v in bones.items()},'clips':[a[1] for t,a in records if t=='AnimationStack'],'meshes':[a[1] for t,a in records if t=='Model' and len(a)>2 and a[2]=='Mesh']}

def slug(v):return re.sub('[^a-z0-9]+','_',v.lower()).strip('_')
files=sorted(p for p in Path('Assets').rglob('*') if p.is_file()); assets={}; rigs={}; textures=[]
for p in files:
    ext=p.suffix.lower()
    if ext in ['.png','.jpg','.jpeg']:textures.append(str(p));continue
    if ext not in ['.fbx','.glb']:continue
    key=slug(p.parts[1])+'.'+slug(p.stem);d={'path':str(p)}
    if ext=='.fbx':meta=inspect_fbx(p)
    else:
        with p.open('rb') as f:f.seek(12);n,_=struct.unpack('<II',f.read(8));g=json.loads(f.read(n))
        meta={'clips':[a['name'] for a in g.get('animations',[])],'bones':{},'meshes':[a.get('name') for a in g.get('nodes',[]) if 'mesh'in a]}
    rigs[str(p)]=meta;d['clips']=meta['clips'];assets[key if key not in assets else key+'.'+ext[1:]]=d
# Use GLB by default for packs with both formats.
for k in list(assets):
    if k.endswith('.glb'):assets[k[:-4]+'.fbx']=assets[k[:-4]];assets[k[:-4]]=assets.pop(k)
assets={k:v for k,v in assets.items() if rigs[v['path']]['meshes'] or rigs[v['path']]['clips']}
sounds=sorted(str(p) for p in Path('SoundEffects').rglob('*') if p.suffix.lower() in {'.wav','.ogg','.mp3','.m4a','.aac','.flac'})
Path('src/catalog.js').write_text('// Generated by scripts/catalog.py\nexport const MODELS = '+json.dumps(assets,indent=1)+';\nexport const TEXTURES = '+json.dumps(textures,indent=1)+';\nexport const SOUNDS = '+json.dumps(sounds)+';\n');Path('docs/asset-inventory.json').write_text(json.dumps({'files':list(map(str,files)),'models':rigs,'sounds':sounds},indent=1));print(len(files),'files;',len(assets),'models;',len(textures),'textures;',len(sounds),'sounds');print('ghost',assets['halloween.character_ghost'],rigs[assets['halloween.character_ghost']['path']]);print('male',assets['male.character_01'])
